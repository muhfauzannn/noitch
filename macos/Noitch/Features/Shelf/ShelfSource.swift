import AppKit
import CryptoKit
import os

/// The only periodic exception here is the explicitly approved 1 s clipboard check.
final class ShelfSource {
    private static let logger = Logger(subsystem: "app.noitch.mac", category: "Shelf")
    private let directory: URL
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    private var timer: Timer?
    var onCapture: ((ShelfItem) -> Void)?
    private let marker = NSPasteboard.PasteboardType("app.noitch.clipboard")
    private let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]

    init(pasteboard: NSPasteboard = .general, directory: URL? = nil) {
        self.pasteboard = pasteboard
        self.directory = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Noitch/Shelf", isDirectory: true)
        lastChange = pasteboard.changeCount
    }

    func setRecording(_ recording: Bool) {
        timer?.invalidate()
        timer = nil
        guard recording else { return }
        lastChange = pasteboard.changeCount
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.capture() }
        }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() { timer?.invalidate(); timer = nil }

    func load() -> ShelfCollection {
        guard let data = try? Data(contentsOf: directory.appendingPathComponent("items.json")), data.count <= 2_000_000,
              let state = try? JSONDecoder().decode(ShelfCollection.self, from: data) else { return ShelfCollection() }
        return ShelfCollection(files: Array(state.files.prefix(50)), clipboard: Array(state.clipboard.prefix(50)))
    }

    func save(_ collection: ShelfCollection) {
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try JSONEncoder().encode(collection).write(to: directory.appendingPathComponent("items.json"), options: .atomic)
            var keep = Set((collection.files + collection.clipboard).map(\.payload).filter { !$0.isEmpty })
            for path in (collection.files + collection.clipboard).flatMap(\.files) {
                let file = URL(fileURLWithPath: path)
                if file.deletingLastPathComponent().standardizedFileURL == directory.standardizedFileURL { keep.insert(file.lastPathComponent) }
            }
            for file in (try? FileManager.default.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? [] {
                if file.lastPathComponent.hasPrefix("payload-") && !keep.contains(file.lastPathComponent) { try? FileManager.default.removeItem(at: file) }
            }
        } catch { Self.logger.error("Shelf save failed: \(error.localizedDescription)") }
    }

    func fileItem(_ urls: [URL]) -> ShelfItem? {
        let files = Array(urls.filter(\.isFileURL).prefix(16))
        guard let first = files.first else { return nil }
        let paths = files.map(\.path)
        return ShelfItem(id: digest(Data(paths.joined(separator: "\n").utf8)), kind: .files,
                         title: files.count == 1 ? first.lastPathComponent : "\(files.count) files",
                         preview: String(files.map(\.lastPathComponent).joined(separator: ", ").prefix(300)), files: paths)
    }

    private func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    private func stored(_ data: Data, kind: ShelfItem.Kind, title: String, preview: String, fileExtension: String? = nil) -> ShelfItem? {
        let id = kind.rawValue + "-" + digest(data)
        let name = "payload-" + id + "." + (fileExtension ?? (kind == .image ? "png" : "txt"))
        do {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            try data.write(to: directory.appendingPathComponent(name), options: .atomic)
            return ShelfItem(id: id, kind: kind, title: title, preview: preview, payload: name)
        } catch { Self.logger.error("Clipboard storage failed: \(error.localizedDescription)"); return nil }
    }

    @discardableResult
    func capture(force: Bool = false) -> ShelfItem? {
        guard force || pasteboard.changeCount != lastChange else { return nil }
        lastChange = pasteboard.changeCount
        let types = pasteboard.types ?? []
        guard !types.contains(marker), !types.contains(where: { privateTypes.contains($0.rawValue) }) else { return nil }
        let item: ShelfItem?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = fileItem(urls)
        } else if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, string.utf8.count <= 64_000 {
            let url = URL(string: string.trimmingCharacters(in: .whitespacesAndNewlines))
            let link = !string.contains(where: \.isWhitespace) && ["http", "https"].contains(url?.scheme?.lowercased() ?? "") && url?.host != nil
            item = stored(Data(string.utf8), kind: link ? .link : .text, title: link ? (url?.host ?? "Link") : "Text", preview: String(string.prefix(300)))
        } else if let png = pasteboard.data(forType: .png), png.count <= 4_000_000 {
            item = stored(png, kind: .image, title: "Copied image", preview: "PNG image")
        } else if let tiff = pasteboard.data(forType: .tiff), tiff.count <= 4_000_000 {
            item = stored(tiff, kind: .image, title: "Copied image", preview: "TIFF image", fileExtension: "tiff")
        } else { item = nil }
        if let item { onCapture?(item) }
        return item
    }

    func data(for item: ShelfItem) -> Data? {
        guard item.payload.hasPrefix("payload-"), !item.payload.contains("/"), !item.payload.contains("\\") else { return nil }
        return try? Data(contentsOf: directory.appendingPathComponent(item.payload))
    }

    func copy(_ item: ShelfItem) -> Bool {
        let data = item.kind == .files ? nil : data(for: item)
        guard item.kind == .files || data != nil else { return false }
        if item.kind == .files && !item.files.allSatisfy({ FileManager.default.fileExists(atPath: $0) }) { return false }
        pasteboard.clearContents()
        let success: Bool
        if item.kind == .files {
            success = pasteboard.writeObjects(item.files.map { URL(fileURLWithPath: $0) as NSURL })
        } else {
            success = pasteboard.setData(data!, forType: item.kind == .image ? (item.payload.hasSuffix(".tiff") ? .tiff : .png) : .string)
        }
        pasteboard.setData(Data(), forType: marker)
        lastChange = pasteboard.changeCount
        return success
    }

    func draggingItems(_ item: ShelfItem) -> [NSDraggingItem] {
        if item.kind == .files { return item.files.map { NSDraggingItem(pasteboardWriter: NSURL(fileURLWithPath: $0)) } }
        guard let data = data(for: item) else { return [] }
        if item.kind == .image { return [NSDraggingItem(pasteboardWriter: directory.appendingPathComponent(item.payload) as NSURL)] }
        guard let text = String(data: data, encoding: .utf8) else { return [] }
        return [NSDraggingItem(pasteboardWriter: text as NSString)]
    }
}
